function slug(model) {
  return 'stamford-' + model.toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
}

function parseSeries(model) {
  if (model.startsWith('P80 LVSI804')) return 'P80 LVSI804'
  if (model.startsWith('S7L1D'))  return 'S7L1D'
  if (model.startsWith('S6L1D'))  return 'S6L1D'
  if (model.startsWith('S5L1D'))  return 'S5L1D'
  if (model.startsWith('S5L1S'))  return 'S5L1S'
  if (model.startsWith('S4L1D'))  return 'S4L1D'
  if (model.startsWith('S4L1S'))  return 'S4L1S'
  if (model.startsWith('HCI634')) return 'HCI634'
  if (model.startsWith('HCI544')) return 'HCI544'
  if (model.startsWith('HCI444')) return 'HCI444'
  if (model.startsWith('PI734'))  return 'PI734'
  if (model.startsWith('UCDI274')) return 'UCDI274'
  if (model.startsWith('UCI274')) return 'UCI274'
  if (model.startsWith('UCI224')) return 'UCI224'
  if (model.startsWith('PI144'))  return 'PI144'
  if (model.startsWith('PI044'))  return 'PI044'
  if (model.startsWith('S1L2'))   return 'S1L2'
  if (model.startsWith('S0L2'))   return 'S0L2'
  if (model.startsWith('S0L1'))   return 'S0L1'
  return null
}

